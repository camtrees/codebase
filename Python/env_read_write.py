from dotenv import set_key, load_dotenv
import os

#------------------------------------------------------------------------------------------
# Load existing environment variables
#------------------------------------------------------------------------------------------
load_dotenv()

#------------------------------------------------------------------------------------------
# Read a Key
#------------------------------------------------------------------------------------------
def env_read_key(key):
    return os.getenv(key)

#------------------------------------------------------------------------------------------
# Write a Key
#------------------------------------------------------------------------------------------
def env_write_key(key, value):
    return set_key(dotenv_path=".env", key_to_set=key, value_to_set=value)
